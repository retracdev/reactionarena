/*
 * The pages behind shared links, and the social card each one shows. Pure data and string
 * building, so tests can check the committed files without a browser.
 */
import { GAMES } from '../../js/games/index.js';
import { SITE } from '../../js/share.js';

const COLLECTION = 'Part of the retrac.space collection.';

export const CARDS_DIR = 'assets/social';

/** Every share page: where it's written, where it sends visitors, and its card. */
export function sharePages() {
  return [
    {
      file: 'index.html',
      url: `${SITE}/`,
      title: 'Reaction Arena',
      description: `Ten quick browser challenges for reflexes, memory, focus and precision. ${COLLECTION}`,
      image: 'home.jpg',
      imageAlt: 'Reaction Arena: how quick is your mind, really?',
      card: { kind: 'home' },
    },
    {
      file: 'leaderboards/index.html',
      url: `${SITE}/leaderboards/`,
      redirect: '/#/leaderboards',
      title: 'Leaderboards · Reaction Arena',
      description: `See who's fastest across all ten Reaction Arena tests. ${COLLECTION}`,
      image: 'leaderboards.jpg',
      imageAlt: 'Reaction Arena leaderboards',
      card: { kind: 'leaderboards' },
    },
    ...GAMES.map((g) => ({
      file: `test/${g.id}/index.html`,
      url: `${SITE}/test/${g.id}/`,
      redirect: `/#/${g.id}`,
      title: `${g.name} · Reaction Arena`,
      description: `${g.tagline} A free browser test from Reaction Arena. ${COLLECTION}`,
      image: `tests/${g.id}.jpg`,
      imageAlt: `${g.name}: ${g.tagline}`,
      card: { kind: 'test', id: g.id },
    })),
  ];
}

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/** The Open Graph and Twitter tags for a page. Shared by index.html and every share page. */
export function metaTags(page) {
  const image = `${SITE}/${CARDS_DIR}/${page.image}`;
  return [
    `<link rel="canonical" href="${esc(page.url)}">`,
    `<meta property="og:site_name" content="Reaction Arena">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:title" content="${esc(page.title)}">`,
    `<meta property="og:description" content="${esc(page.description)}">`,
    `<meta property="og:url" content="${esc(page.url)}">`,
    `<meta property="og:image" content="${esc(image)}">`,
    `<meta property="og:image:type" content="image/jpeg">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(page.imageAlt)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(page.title)}">`,
    `<meta name="twitter:description" content="${esc(page.description)}">`,
    `<meta name="twitter:image" content="${esc(image)}">`,
    `<meta name="twitter:image:alt" content="${esc(page.imageAlt)}">`,
  ];
}

/** A tiny page that link previews read and people pass straight through. */
export function sharePageHtml(page) {
  const meta = metaTags(page).map((tag) => `  ${tag}`).join('\n');
  return `<!doctype html>
<!-- Generated by \`npm run build:social\`. Edit scripts/social/pages.mjs, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
  <title>${esc(page.title)}</title>
  <meta name="description" content="${esc(page.description)}">
  <meta name="theme-color" content="#0a0b09">
${meta}
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <meta http-equiv="refresh" content="0; url=${esc(page.redirect)}">
  <script>location.replace(${JSON.stringify(page.redirect)});</script>
  <style>body{margin:0;min-height:100vh;display:grid;place-items:center;background:#0a0b09;color:#b7bdb0;font:16px system-ui,sans-serif}a{color:#b5ef5a}</style>
</head>
<body>
  <p>Opening <a href="${esc(page.redirect)}">${esc(page.title)}</a>…</p>
</body>
</html>
`;
}

// Marks the generated block of tags in index.html so the build can refresh it in place.
export const META_START = '<!-- social:start (generated by `npm run build:social`) -->';
export const META_END = '<!-- social:end -->';

export function homeMetaBlock() {
  const home = sharePages()[0];
  return [META_START, ...metaTags(home), META_END].map((line) => `  ${line}`).join('\n');
}
